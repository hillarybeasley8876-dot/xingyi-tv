def jstr(s):
    if s is None:
        return 'null'
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def jsplits(splits):
    return 'new String[][]{' + ', '.join('{%s, %s}' % (jstr(a), jstr(t)) for a, t in splits) + '}'


