def resolver_test():
    rows = []
    for u in RESOLVE_CASES:
        it = R.parse(u)
        assert it and it['kind'] in ('SONG', 'ARTIST'), u
        pick, asked = R.resolve(it, lambda q: FIX['songs'].get(q, {'code': 200, 'result': {'songCount': 0, 'songs': []}}))
        qs = R.queries(it)
        rows.append('        resolveCase(%s, %s, %s, %s, new String[]{%s}, new String[]{%s}, %s, %s);' % (
            jstr(u), jstr(it['content']), jsplits(it['splits']), str(it['wantsVersion']).lower(),
            ', '.join(jstr(q) for q in qs), ', '.join(jstr(q) for q in asked),
            ('%dL' % pick['id']) if pick else '0L', str(bool(pick and pick['confident'])).lower()))
    norm_rows = '\n'.join('        eq("norm", %s, MusicResolver.norm(%s), %s);' % (jstr(x), jstr(x), jstr(R.norm(x))) for x in NORM)
    base_rows = '\n'.join('        eq("baseTitle", %s, MusicResolver.baseTitle(%s), %s);' % (jstr(x), jstr(x), jstr(R.base_title(x))) for x in BASE)
    tag_rows = '\n'.join('        check(MusicResolver.titleTagged(%s) == %s, "titleTagged(%s) should be %s");' % (
        jstr(x), str(R.title_tagged(x)).lower(), x.replace('"', "'"), str(R.title_tagged(x)).lower()) for x in TAGGED)
    album_rows = '\n'.join('        check(MusicResolver.albumTagged(%s) == %s, "albumTagged(%s) should be %s");' % (
        jstr(x), str(bool(R.ALBUM_VERSION.search(x))).lower(), x, str(bool(R.ALBUM_VERSION.search(x))).lower()) for x in ALBUMS)
    sim_rows = '\n'.join('        near("similarity(%s,%s)", MusicResolver.similarity(%s, %s), %.6f);' % (a, b, jstr(a), jstr(b), R.similarity(a, b)) for a, b in SIMS)
    body = '\n'.join(rows)
