"""Generates src/xyz/erapi0neer/xingyi/agent/AlmanacData.java from lunar_python (6tail, MIT): the lunar months of
1900-2100, the 24 solar terms of 1950-2100 (Beijing time) and the State Council's holiday schedules the library carries.

python tests/agent/almanac_gen.py            write the data file
python tests/agent/almanac_gen.py --expect   also write assistant-out/tmp/almanac-expect.txt (every day 1950-2100) for
                                              AlmanacVerify, the exhaustive check of Almanac.java against the library

pip install --user lunar_python   (1.4.9, 2026-11-05, has the 2027 schedule published that day)
"""
import os, sys

from lunar_python import LunarYear, Solar
from lunar_python.util import HolidayUtil

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "xyz", "erapi0neer", "xingyi", "agent", "AlmanacData.java")
EXPECT = r"H:\tools\mitv\voice\assistant-out\tmp\almanac-expect.txt"
TERMS = ["小寒", "大寒", "立春", "雨水", "惊蛰", "春分", "清明", "谷雨", "立夏", "小满", "芒种", "夏至",
         "小暑", "大暑", "立秋", "处暑", "白露", "秋分", "寒露", "霜降", "立冬", "小雪", "大雪", "冬至"]
HOLIDAY_YEARS = (2025, 2026, 2027)


def lunar_years():
    """One int a year: bit i = the i-th month of the year (in order, the leap month in its place) has 30 days;
    bits 13-16 = the leap month (0: none)."""
    out = []
    for y in range(1900, 2101):
        bits, leap = 0, 0
        for i, m in enumerate(LunarYear.fromYear(y).getMonthsInYear()):
            if m.getDayCount() == 30:
                bits |= 1 << i
            if m.getMonth() < 0:
                leap = -m.getMonth()
        out.append(bits | (leap << 13))
    first = LunarYear.fromYear(1900).getMonthsInYear()[0]
    assert Solar.fromJulianDay(first.getFirstJulianDay()).toYmd() == "1900-01-31"
    return out


def term_days():
    """48 digits a year from 1950: the day of the month of each term, two a month in TERMS order."""
    rows = []
    for y in range(1950, 2101):
        days = {}
        for m in range(1, 13):
            for d in range(1, 32):
                try:
                    s = Solar.fromYmd(y, m, d)
                except Exception:
                    break
                if s.getMonth() != m:
                    break
                t = s.getLunar().getJieQi()
                if t:
                    days[t] = (m, d)
        row = ""
        for i, name in enumerate(TERMS):
            m, d = days[name]
            assert m == i // 2 + 1, (y, name, m)
            row += "%02d" % d
        rows.append(row)
    return rows


def holidays():
    out = []
    for y in HOLIDAY_YEARS:
        for h in HolidayUtil.getHolidays(y):
            out.append("%s%s%s" % (h.getDay().replace("-", ""), "班" if h.isWork() else "休", h.getName()))
    return out


def main():
    years, terms, hols = lunar_years(), term_days(), holidays()
    lines = ["package xyz.erapi0neer.xingyi.agent;", "",
             "/** Generated by tests/agent/almanac_gen.py from lunar_python " + "(6tail, MIT) — do not edit. See Almanac. */",
             "final class AlmanacData {", "    private AlmanacData() { }", "",
             "    /** 1900-2100: bit i = the i-th month of the year has 30 days; bits 13-16 = the leap month (0: none). */",
             "    static final int[] LUNAR = {"]
    for i in range(0, len(years), 10):
        lines.append("        " + ", ".join("0x%05x" % v for v in years[i:i + 10]) + ",")
    lines += ["    };", "",
              "    /** The first year of TERMS. */", "    static final int TERMS_FROM = 1950;",
              "    /** A row a year: the day of the month of each of the 24 terms, two digits each (two terms a month). */",
              "    static final String[] TERMS = {"]
    for i in range(0, len(terms), 2):
        lines.append("        " + ", ".join('"%s"' % r for r in terms[i:i + 2]) + ",")
    lines += ["    };", "",
              "    /** The State Council's schedules (" + ", ".join(str(y) for y in HOLIDAY_YEARS)
              + "): yyyyMMdd, 休 (a day off) or 班 (a working day moved), and the holiday's name. */",
              "    static final String[] HOLIDAYS = {"]
    for i in range(0, len(hols), 4):
        lines.append("        " + ", ".join('"%s"' % h for h in hols[i:i + 4]) + ",")
    lines += ["    };", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT, len(years), "years,", len(terms), "term rows,", len(hols), "holiday days")
    if "--expect" in sys.argv:
        os.makedirs(os.path.dirname(EXPECT), exist_ok=True)
        n = 0
        with open(EXPECT, "w", encoding="utf-8", newline="\n") as f:
            s = Solar.fromYmd(1950, 1, 1)
            while s.getYear() <= 2100:
                l = s.getLunar()
                f.write("%s %d %d %d %s\n" % (s.toYmd(), l.getYear(), l.getMonth(), l.getDay(), l.getJieQi() or "-"))
                s = s.next(1)
                n += 1
        print("wrote", EXPECT, n, "days")


if __name__ == "__main__":
    main()
