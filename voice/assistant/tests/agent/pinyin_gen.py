"""Generates src/xyz/erapi0neer/xingyi/agent/PinyinData.java from pypinyin: every reading of GB2312's 6763 Chinese
characters, toneless, lower case, most common first (「朴」→ pu, piao, po). 星仪 needs it to search a stock again by how a
misheard name sounds (「质朴」 → zhipu → 智谱, 2026-11-07).

python tests/agent/pinyin_gen.py            write the data file
python tests/agent/pinyin_gen.py --check    regenerate in memory and compare with the file on disk
                                            (prints PINYIN DATA OK, exit 0 / PINYIN DATA STALE, exit 1)

pypinyin 0.55.0 is installed for python on this machine; do not install anything.
"""
import os
import sys

import pypinyin

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "xyz", "erapi0neer", "xingyi", "agent", "PinyinData.java")
PER_CHUNK = 1500


def entries():
    """Every GB2312 Chinese character with its readings, in code-point order: 0xB0-0xF7 rows, 0xA1-0xFE columns."""
    out = []
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            readings = []
            for r in pypinyin.pinyin(ch, style=pypinyin.Style.NORMAL, heteronym=True)[0]:
                r = r.lower()
                if r not in readings:
                    readings.append(r)
            if readings:
                out.append(ch + ",".join(readings) + ";")
    return out


def chunks():
    """The entries packed into Java string constants: a Chinese character takes 3 bytes of modified UTF-8 and a
    constant must stay under 65535, so at most PER_CHUNK entries a chunk."""
    items = entries()
    return [items[i:i + PER_CHUNK] for i in range(0, len(items), PER_CHUNK)]


def source():
    rows = chunks()
    lines = ["package xyz.erapi0neer.xingyi.agent;", "",
             "/** Generated by tests/agent/pinyin_gen.py from pypinyin %s: GB2312's %d characters. Do not edit. */"
             % (pypinyin.__version__, sum(len(r) for r in rows)),
             "final class PinyinData {", "    private PinyinData() { }", "",
             "    /** 「<character><reading>[,<reading>…];」 in code-point order; Pinyin parses them once. */",
             "    static final String[] CHUNKS = {"]
    for row in rows:
        lines.append('        "' + "".join(row) + '",')
    lines += ["    };", "}", ""]
    return "\n".join(lines)


def main():
    text = source()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8", newline="") as f:
            on_disk = f.read()
        if on_disk == text:
            print("PINYIN DATA OK")
            return 0
        print("PINYIN DATA STALE")
        return 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT, sum(len(r) for r in chunks()), "characters in", len(chunks()), "chunks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
