#!/bin/sh
# Acceptance for job names-by-sound: the pinyin table is what the generator makes, the TV app builds with this tree's
# sources (the bridge's build.sh also compiles agent/tv), the bridge's JVM suite passes against them, the API the lead
# relies on is there, and the core stays pure. Builds into the bridge's build-wt-names/ so parallel jobs do not collide.
# Prints "NAMES OK".
# A native .exe (python, node, aapt2) reads Git Bash's /h/... as H:\h\... while the launching shell has
# MSYS_NO_PATHCONV=1 (the m31w runner's shell does): clear it, so this script does not depend on who ran it.
unset MSYS_NO_PATHCONV 2>/dev/null || true
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
A="$ROOT/src/xyz/erapi0neer/xingyi/agent"
BRIDGE=/h/tools/mitv/xiaoai-bridge
mkdir -p "$ROOT/build"
ok=1
(cd "$ROOT" && PYTHONUTF8=1 python tests/agent/pinyin_gen.py --check) | grep -q "PINYIN DATA OK" || { echo "pinyin_gen.py --check did not print PINYIN DATA OK"; ok=0; }
if ! XINGYI="$ROOT" BRIDGE_BUILD=build-wt-names sh "$BRIDGE/build.sh" > "$ROOT/build/accept-bridge-build.log" 2>&1; then
    echo "bridge build FAILED:"; grep -v -E "^(注|ע):" "$ROOT/build/accept-bridge-build.log" | tail -25; ok=0
fi
if ! XINGYI="$ROOT" BRIDGE_BUILD=build-wt-names sh "$BRIDGE/tests/run_all.sh" > "$ROOT/build/accept-bridge-jvm.log" 2>&1; then
    echo "bridge JVM suite FAILED:"; grep -E "FAIL|error|错误" "$ROOT/build/accept-bridge-jvm.log" | head -25; ok=0
fi
check() { grep -q -F "$2" "$A/$1" 2>/dev/null || { echo "missing in $1: $2"; ok=0; }; }
check Pinyin.java 'public static List<String> readings(char c)'
check Pinyin.java 'public static boolean hasChinese(String s)'
check Pinyin.java 'public static String spell(String s)'
check Pinyin.java 'public static String initials(String s)'
check Pinyin.java 'public static boolean sameSound(String a, String b)'
check Pinyin.java 'public static int soundIndex(String a, String b)'
check PinyinData.java 'Generated by tests/agent/pinyin_gen.py'
check PinyinData.java 'static final String[] CHUNKS'
check Quotes.java 'public static Hit bySound(String searchText, String query)'
check Quotes.java 'public static final class Hit'
check tv/TvTools.java 'Quotes.bySound('
check tv/TvTools.java 'heard_as'
for f in Pinyin.java PinyinData.java Quotes.java; do
    grep -q "import android\." "$A/$f" && { echo "$f must stay pure (no android.*)"; ok=0; }
done
[ $ok = 1 ] && echo NAMES OK
